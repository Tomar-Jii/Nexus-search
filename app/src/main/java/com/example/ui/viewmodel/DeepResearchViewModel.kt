package com.example.ui.viewmodel

import androidx.lifecycle.ViewModel
import androidx.lifecycle.ViewModelProvider
import androidx.lifecycle.viewModelScope
import com.example.core.database.dao.ResearchReportDao
import com.example.core.database.entity.ResearchReportEntity
import com.example.core.deepresearch.DeepResearchEngine
import com.example.core.model.DeepResearchReport
import com.example.core.model.ResearchDepth
import com.example.core.model.ResearchStage
import kotlinx.coroutines.Job
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.SharingStarted
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.catch
import kotlinx.coroutines.flow.stateIn
import kotlinx.coroutines.launch

class DeepResearchViewModel(
    private val reportDao: ResearchReportDao
) : ViewModel() {

    private val _topic = MutableStateFlow("")
    val topic: StateFlow<String> = _topic.asStateFlow()

    private val _selectedDepth = MutableStateFlow(ResearchDepth.DEEP)
    val selectedDepth: StateFlow<ResearchDepth> = _selectedDepth.asStateFlow()

    private val _currentReport = MutableStateFlow<DeepResearchReport?>(null)
    val currentReport: StateFlow<DeepResearchReport?> = _currentReport.asStateFlow()

    val savedReports: StateFlow<List<ResearchReportEntity>> = reportDao.getAllReports()
        .stateIn(viewModelScope, SharingStarted.WhileSubscribed(5000), emptyList())

    private var researchJob: Job? = null

    fun onTopicChange(newTopic: String) {
        _topic.value = newTopic
    }

    fun setDepth(depth: ResearchDepth) {
        _selectedDepth.value = depth
    }

    fun startResearch(searchTopic: String = _topic.value, depth: ResearchDepth = _selectedDepth.value) {
        val clean = searchTopic.trim()
        if (clean.isBlank()) return

        _topic.value = clean
        _selectedDepth.value = depth

        researchJob?.cancel()
        researchJob = viewModelScope.launch {
            DeepResearchEngine.executeDeepResearch(clean, depth, reportDao)
                .catch { e ->
                    _currentReport.value = _currentReport.value?.copy(
                        stage = ResearchStage.FAILED,
                        summary = "Research failed: ${e.localizedMessage}"
                    )
                }
                .collect { report ->
                    _currentReport.value = report
                }
        }
    }

    fun deleteReport(reportId: String) {
        viewModelScope.launch {
            reportDao.deleteReport(reportId)
            if (_currentReport.value?.id == reportId) {
                _currentReport.value = null
            }
        }
    }

    fun generateMarkdownReport(report: DeepResearchReport): String {
        return buildString {
            append("# NEXUS RESEARCH REPORT: ${report.mainTopic}\n\n")
            append("**Research Depth:** ${report.depth.label}  \n")
            append("**Confidence Score:** ${report.confidenceScore}% (${report.confidenceExplanation})  \n")
            append("**Completed:** ${java.util.Date(report.timestamp)}\n\n")
            append("## Executive Summary\n\n")
            append("${report.summary}\n\n")
            append("## Key Findings\n\n")
            report.keyFindings.forEach { append("- $it\n") }
            append("\n")
            if (report.contradictoryFindings.isNotEmpty()) {
                append("## Observed Contradictions & Trade-Offs\n\n")
                report.contradictoryFindings.forEach { append("- $it\n") }
                append("\n")
            }
            append("## Verified Source Citations\n\n")
            report.sources.forEach { c ->
                append("[${c.index}] **${c.title}** (${c.domain})\nURL: ${c.url}\n\n")
            }
            append("---\n*Generated by NEXUS SEARCH 2.0 (Death Game Boy 375)*\n")
        }
    }
}

class DeepResearchViewModelFactory(
    private val reportDao: ResearchReportDao
) : ViewModelProvider.Factory {
    @Suppress("UNCHECKED_CAST")
    override fun <T : ViewModel> create(modelClass: Class<T>): T {
        return DeepResearchViewModel(reportDao) as T
    }
}
